// Translate returns a Kiswahili equivalent for fixed document labels when the
// requested output language is Swahili. User-authored CV content is never passed
// through this function.
func Translate(language, value string) string {
	if language != "sw" {
		return value
	}
	if translated, ok := swahiliLabels[value]; ok {
		return translated
	}
	return value
}

